// ansi16Indices maps ANSI16 names to their xterm256 palette indices.
// The first 16 entries of xterm256Palette correspond to the ANSI16 set.
var ansi16Indices = map[string]uint8{
	"black":          0,
	"red":            1,
	"green":          2,
	"yellow":         3,
	"blue":           4,
	"magenta":        5,
	"cyan":           6,
	"white":          7,
	"bright-black":   8,
	"bright-red":     9,
	"bright-green":   10,
	"bright-yellow":  11,
	"bright-blue":    12,
	"bright-magenta": 13,
	"bright-cyan":    14,
	"bright-white":   15,
}

// NearestAnsi256 returns the xterm ANSI256 palette index (0-255)
// whose RGB value is closest to c, measured by Euclidean distance
// in RGB space.
func NearestAnsi256(c color.Color) uint8 {
	r, g, b, _ := c.RGBA()
	// RGBA returns 16-bit values; convert to 8-bit.
	cr := float64(r >> 8)
	cg := float64(g >> 8)
	cb := float64(b >> 8)

	bestIdx := uint8(0)
	bestDist := math.MaxFloat64

	for i, entry := range xterm256Palette {
		dr := cr - float64(entry[0])
		dg := cg - float64(entry[1])
		db := cb - float64(entry[2])
		dist := dr*dr + dg*dg + db*db
		if dist < bestDist {
			bestDist = dist
			bestIdx = uint8(i)
		}
	}

	return bestIdx
}

// NearestAnsi16Name returns the ANSI16 colour name (e.g. "cyan")
// whose canonical hex value is closest to c, measured by Euclidean
// distance in RGB space.
func NearestAnsi16Name(c color.Color) string {
	r, g, b, _ := c.RGBA()
	cr := float64(r >> 8)
	cg := float64(g >> 8)
	cb := float64(b >> 8)

	bestName := "black"
	bestDist := math.MaxFloat64

	for name, idx := range ansi16Indices {
		entry := xterm256Palette[idx]
		dr := cr - float64(entry[0])
		dg := cg - float64(entry[1])
		db := cb - float64(entry[2])
		dist := dr*dr + dg*dg + db*db
		if dist < bestDist {
			bestDist = dist
			bestName = name
		}
	}

	return bestName
}
